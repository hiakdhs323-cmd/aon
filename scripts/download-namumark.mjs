import { mkdir, writeFile, copyFile } from "node:fs/promises";
const url = "https://raw.githubusercontent.com/uiovasot/namumark/6d8bd559734c173ae1b728f858a7c9f15e6a77f7/namumark.wasm";
const response = await fetch(url);
if (!response.ok) throw new Error("WASM download failed: " + response.status);
const bytes = new Uint8Array(await response.arrayBuffer());
if (bytes.length < 1024 || bytes[0] !== 0 || bytes[1] !== 97 || bytes[2] !== 115 || bytes[3] !== 109) throw new Error("Invalid WebAssembly module.");
await mkdir(".cache", { recursive: true });
await mkdir("static", { recursive: true });
await writeFile(".cache/namumark.wasm", bytes);
await copyFile(".cache/namumark.wasm", "static/namumark.wasm");
console.log("Pinned NamuMark WASM ready: " + bytes.length + " bytes.");
